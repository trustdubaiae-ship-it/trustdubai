// Regenerates public/fonts/tabler-icons.subset.css from the icons this site
// actually uses.  Run with `npm run icons` after adding or removing an icon.
//
// Why: the published @tabler/icons-webfont stylesheet is 211 KB of ~5,800 icons
// and was loaded render-blocking from cdn.jsdelivr.net, a third-party origin
// costing a full DNS+TLS handshake before first paint (553ms measured cold).
// This site uses 68 of those icons, so the subset is ~3 KB and same-origin.
//
// This script EXITS NONZERO if it cannot find a class that the source uses, so a
// newly added icon fails the build rather than silently rendering as nothing.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { join, dirname, resolve, extname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const VERSION = '3.46.0'                        // keep in step with the woff2 in public/fonts
const CSS_URL = `https://cdn.jsdelivr.net/npm/@tabler/icons-webfont@${VERSION}/dist/tabler-icons.min.css`
const OUT = join(ROOT, 'public/fonts/tabler-icons.subset.css')

// The webfont build ships no -filled variants — those live in a separate font.
// The site uses one anyway, so it has never rendered; alias it to the outline
// glyph rather than leaving the verified badge invisible.
const ALIASES = { 'rosette-discount-check-filled': 'rosette-discount-check' }

function collectUsed() {
  const names = new Set()
  const scan = (file) => {
    for (const m of readFileSync(file, 'utf8').matchAll(/\bti-([a-z0-9-]+)/g)) names.add(m[1])
  }
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const p = join(dir, entry)
      if (statSync(p).isDirectory()) walk(p)
      else if (['.js', '.jsx'].includes(extname(p))) scan(p)
    }
  }
  walk(join(ROOT, 'src'))
  scan(join(ROOT, 'index.html'))
  return [...names].sort()
}

const used = collectUsed()
const css = await fetch(CSS_URL).then((r) => {
  if (!r.ok) throw new Error(`could not fetch tabler CSS: HTTP ${r.status}`)
  return r.text()
})

const rule = (name) => css.match(new RegExp(`\\.ti-${name.replace(/-/g, '\\-')}:before\\{[^}]*\\}`))?.[0]
const base = css.match(/\.ti\s*\{[^}]*\}/)?.[0]
if (!base) { console.error('! could not find the base .ti rule — tabler CSS format changed?'); process.exit(1) }

const out = [
  `/* GENERATED by scripts/gen-icon-subset.mjs from @tabler/icons-webfont ${VERSION}.`,
  '   Do not edit by hand — run `npm run icons`. */',
  `@font-face{font-family:"tabler-icons";font-style:normal;font-weight:400;font-display:block;src:url("/fonts/tabler-icons.woff2?v${VERSION}") format("woff2")}`,
  base,
]
const missing = []
for (const name of used) {
  const found = rule(name) || (ALIASES[name] && rule(ALIASES[name])?.replace(`.ti-${ALIASES[name]}:before`, `.ti-${name}:before`))
  if (found) out.push(found)
  else missing.push(name)
}

if (missing.length) {
  console.error(`! ${missing.length} icon(s) used in source but not in tabler ${VERSION}:`)
  console.error('  ' + missing.join(' '))
  console.error('  Fix the class name, or add an alias in ALIASES, then re-run.')
  process.exit(1)
}

writeFileSync(OUT, out.join('\n') + '\n')
console.log(`Wrote ${OUT.replace(ROOT + '\\', '').replace(ROOT + '/', '')} — ${used.length} icons, ${(Buffer.byteLength(out.join('\n')) / 1024).toFixed(1)} KB (full stylesheet is 206 KB).`)
